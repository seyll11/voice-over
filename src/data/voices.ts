export function normalizeVoiceId(raw?: string | null): VoiceProfile['id'] {
  if (!raw) return 'Kore';
  const mapped = LEGACY_VOICE_MAP[raw] || raw;
  const found = VOICES.find((v) => v.id === mapped);
  return found ? found.id : 'Kore';
}

